// Render tests for the Compact_Top_Bar icons, and the ASSETS.md coverage of
// icons.tsx (R15.2, the same record assets.test.ts keeps for component files).

import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";

import { MotionIcon, SkipIcon } from "./icons";

const ASSETS_MD = readFileSync(resolve(__dirname, "..", "ASSETS.md"), "utf8");

describe("MotionIcon", () => {
  it("draws a wave in currentColor, with no fill colour of its own", () => {
    const html = renderToStaticMarkup(createElement(MotionIcon));
    expect(html).toContain('data-icon="motion"');
    expect(html).toContain('stroke="currentColor"');
    expect(html).toContain('fill="none"');
  });

  it("adds a slash when motion is off", () => {
    const on = renderToStaticMarkup(createElement(MotionIcon, { off: false }));
    const off = renderToStaticMarkup(createElement(MotionIcon, { off: true }));
    expect(on.match(/<path/g)?.length).toBe(1);
    expect(off.match(/<path/g)?.length).toBe(2);
  });

  it("is hidden from assistive technology, because its button carries the name", () => {
    expect(renderToStaticMarkup(createElement(MotionIcon))).toContain('aria-hidden="true"');
  });
});

describe("SkipIcon", () => {
  it("draws two forward triangles in currentColor", () => {
    const html = renderToStaticMarkup(createElement(SkipIcon));
    expect(html).toContain('data-icon="skip"');
    expect(html.match(/<path/g)?.length).toBe(2);
    expect(html).toContain('stroke="currentColor"');
  });

  it("is hidden from assistive technology", () => {
    expect(renderToStaticMarkup(createElement(SkipIcon))).toContain('aria-hidden="true"');
  });
});

describe("ASSETS.md coverage of icons.tsx", () => {
  const rows = ASSETS_MD.split("\n").filter((line) =>
    line.startsWith("| src/components/ceremony/scene/icons.tsx |"),
  );

  it("has exactly one row for icons.tsx", () => {
    expect(rows.length).toBe(1);
  });

  it("records the licence as original, not AI-generated", () => {
    const cells = rows[0].split("|").map((c) => c.trim());
    expect(cells[3]).toBe("original");
    expect(rows[0]).not.toMatch(/AI|generated by/i);
  });
});

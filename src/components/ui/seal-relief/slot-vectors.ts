// Feature: 13-the-seal (U1, U10)
//
// Literal slot tables for the seal relief (design.md "1. Seal_Relief").
// The sine and cosine functions can differ in the last bit between engines, so
// the relief never calls them at run time. Each entry is written as a literal
// double, the shortest form that reads back as the same number. Each entry has
// length 1 to about 1e-15, so a unit move along a slot measures 1.0 (the design's
// Property 2 floor is 1 - 1e-9). relief.test.ts checks every entry against the
// built-in sine and cosine to 1e-6.
//
// Convention: a slot at angle a (degrees, clockwise from the top of the seal)
// has an outward unit vector DIR = [sin a, -cos a] and a tangent TAN =
// [cos a, sin a]. Slot 0 points up, towards y = 0 in the 100-unit drawing space.
//
// Tick slots are 11.25 degrees apart, dot slots sit half a slot after them
// (offset 5.625 degrees), and notch slots are 15 degrees apart.

/** A two-number vector, [x, y], in the 100-unit drawing space. */
